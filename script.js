// Tilt on hover (only for mouse-type pointers, and not for reduced motion)
const fine = matchMedia("(hover:hover) and (pointer:fine)").matches && !matchMedia("(prefers-reduced-motion:reduce)").matches;
if (fine) document.querySelectorAll(".proj").forEach(c => {
  c.addEventListener("pointermove", e => {
    const r = c.getBoundingClientRect();
    c.style.setProperty("--ry", ((e.clientX - r.left) / r.width - .5) * 8 + "deg");
    c.style.setProperty("--rx", (.5 - (e.clientY - r.top) / r.height) * 8 + "deg");
  });
  c.addEventListener("pointerleave", () => { c.style.setProperty("--rx", "0deg"); c.style.setProperty("--ry", "0deg"); });
});

// Reveal on scroll
const io = new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); } }), { threshold: .12 });
document.querySelectorAll(".reveal, .bento .card, .envelope").forEach(n => { n.classList.add("reveal"); io.observe(n); });

